                if (wheelTimeout) return;
                
                if (Math.abs(e.deltaY) > 40) {
                    wheelTimeout = setTimeout(() => { wheelTimeout = null; }, 500);
                    if (e.deltaY > 0) openModal(currentIndex + 1, 'up');
                    else openModal(currentIndex - 1, 'down');
                }
            }, { passive: true });
        }

        // Keyboard Arrow Keys
        document.addEventListener('keydown', (e) => {
            if (modal && !modal.classList.contains('pointer-events-none')) {
                if (e.key === 'Escape') closeModal();
                if (e.key === 'ArrowDown' || e.key === 'ArrowRight') openModal(currentIndex + 1, 'up');
                if (e.key === 'ArrowUp' || e.key === 'ArrowLeft') openModal(currentIndex - 1, 'down');
            }
        });

        // Mobile Coverflow Swipe Support on main page
        const mobileStage = document.getElementById('coverflow-mobile-stage');
        if (mobileStage) {
            let touchStartX = 0;
            mobileStage.addEventListener('touchstart', (e) => {
                touchStartX = e.touches[0].clientX;
            }, { passive: true });

            mobileStage.addEventListener('touchend', (e) => {
                const diff = touchStartX - e.changedTouches[0].clientX;
                if (Math.abs(diff) > 40) {
                    if (diff > 0) updateCoverflow(currentIndex + 1);
                    else updateCoverflow(currentIndex - 1);
                }
            }, { passive: true });
        }

        // Autoplay loop all card preview videos on page
        const startCardVideos = () => {
            document.querySelectorAll('.reel-preview-video').forEach(video => {
                video.muted = true;
                video.play().catch(() => {});
            });
        };
        startCardVideos();
        window.addEventListener('scroll', startCardVideos, { once: true, passive: true });
        window.addEventListener('touchstart', startCardVideos, { once: true, passive: true });
    });
</script>
